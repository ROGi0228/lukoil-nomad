import enum


class TaskCriterion(str, enum.Enum):
    """Как считаются баллы за задание — см. PROJECT_PLAN.md, Фаза 15.

    PASS_FAIL — «выполнил/не выполнил», Task.pass_points за факт сдачи.
    SPEED_RANK — «кто первым», авто-баллы по порядку сдачи (Task.rank_points).
    MANUAL — бот собирает вложения (доказательства) через кнопку «Сдать задание»,
    баллы за диспетч команды проставляет админ вручную (голосование по лайкам,
    секундомер координатора на месте и т.п.).
    GLOBAL_MISSION — «глобальная миссия» без сдачи (Критерий №3, вариант «ничего не
    прикладывать»): рассылается один раз, БЕЗ кнопки «Сдать задание» — чисто
    информационное напоминание на весь срок экспедиции, с ежедневным
    повтором-напоминанием, пока не оценено. Баллы проставляет админ вручную в конце
    (например, «Эко-миссия» — мусор физически сдаётся координатору на месте).
    GLOBAL_MISSION_SUBMIT — «глобальная миссия» со сдачей (Критерий №3, вариант
    «в конце нужно прислать итог»): рассылается один раз, С кнопкой «Сдать
    задание» — команда/участник копит вложения на протяжении экспедиции и сдаёт
    итог до дедлайна (например, «2000 км в одном видео»), с теми же ежедневными
    напоминаниями, что и у GLOBAL_MISSION, пока не сдано. Баллы всё равно
    проставляет админ вручную (решение жюри), не автоматика.
    """

    PASS_FAIL = "pass_fail"
    SPEED_RANK = "speed_rank"
    MANUAL = "manual"
    GLOBAL_MISSION = "global_mission"
    GLOBAL_MISSION_SUBMIT = "global_mission_submit"
